@pytest.mark.parametrize("tool,cmd", [(t, c) for t, cs in SHOULD_ASK.items() for c in cs])
def test_adversarial_shell_asks(tool, cmd):
    decision, reason = classify(tool, {"command": cmd}, WS)
    assert decision == "ask", reason


@pytest.mark.parametrize("tool,cmd", [(t, c) for t, cs in SHOULD_ALLOW.items() for c in cs])
def test_everyday_shell_stays_autonomous(tool, cmd):
    decision, reason = classify(tool, {"command": cmd}, WS)
    assert decision == "allow", reason
